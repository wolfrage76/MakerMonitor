        sym = f"icon_{name}_{s}"
        out.append(f"static const uint8_t {sym}_map[] = {{")
        for i in range(0, len(a), s):
            out.append("  " + ",".join(f"0x{b:02x}" for b in a[i:i+s]) + ",")
