"""Digits-only LVGL 8 font for the 7" Today figures (built-in Montserrat stops at 40 px).

    python3 tools/gen_num_font.py Montserrat-Medium.ttf 56 src/font_num_56.c

Montserrat-Medium.ttf: github.com/JulietaUla/Montserrat (OFL), the face LVGL's
built-in fonts are made from. Glyphs: space + , - . 0-9 M k, proportional
(tabular digits left a visible gap after the narrow 1, e.g. "+1 3").
4 bpp, plain bitmap, no kerning, the same format lv_font_conv writes.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

ttf, size, out = sys.argv[1], int(sys.argv[2]), sys.argv[3]
name = f"font_num_{size}"
font = ImageFont.truetype(ttf, size)
chars = " +,-.0123456789Mk"
ascent, descent = font.getmetrics()

bitmap, dsc = [], []
nibbles = []
for ch in chars:
    adv = font.getlength(ch)
    # Ink box: draw on a roomy canvas at a known baseline origin and crop.
    ox, oy = size, 2 * size
    canvas = Image.new("L", (3 * size, 3 * size), 0)
    ImageDraw.Draw(canvas).text((ox, oy), ch, font=font, fill=255, anchor="ls")
    box = canvas.getbbox()
    start = len(nibbles) // 2
    if box:
        x0, y0, x1, y1 = box
        w, h = x1 - x0, y1 - y0
        ofs_x, ofs_y = x0 - ox, oy - y1
        nibbles += [p >> 4 for p in canvas.crop(box).tobytes()]
        if len(nibbles) % 2:  # each glyph starts on a byte
            nibbles.append(0)
    else:
        w = h = ofs_x = ofs_y = 0
    dsc.append((start, round(adv * 16), w, h, ofs_x, ofs_y, ch))
for i in range(0, len(nibbles), 2):
    bitmap.append(nibbles[i] << 4 | nibbles[i + 1])

first = ord(chars[0])
offsets = [ord(c) - first for c in chars]
L = [f"/* Generated by tools/gen_num_font.py from Montserrat Medium {size} px: {chars!r}. */",
     '#include "lvgl.h"', "",
     f"static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {{"]
for i in range(0, len(bitmap), 24):
    L.append("    " + ", ".join(f"0x{b:02x}" for b in bitmap[i:i + 24]) + ",")
L += ["};", "", "static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {",
      "    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0} /* id = 0 reserved */,"]
for s, a, w, h, ox, oy, ch in dsc:
    L.append(f"    {{.bitmap_index = {s}, .adv_w = {a}, .box_w = {w}, .box_h = {h}, .ofs_x = {ox}, .ofs_y = {oy}}}, /* {ch!r} */")
L += ["};", "",
      "static const uint16_t unicode_list_0[] = {" + ", ".join(f"0x{o:x}" for o in offsets) + "};", "",
      "static const lv_font_fmt_txt_cmap_t cmaps[] = {",
      f"    {{.range_start = {first}, .range_length = {offsets[-1] + 1}, .glyph_id_start = 1,",
      f"     .unicode_list = unicode_list_0, .glyph_id_ofs_list = NULL, .list_length = {len(offsets)}, .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}}",
      "};", "",
      "static lv_font_fmt_txt_glyph_cache_t cache;",
      "static const lv_font_fmt_txt_dsc_t font_dsc = {",
      "    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps, .kern_dsc = NULL,",
      "    .kern_scale = 0, .cmap_num = 1, .bpp = 4, .kern_classes = 0, .bitmap_format = 0, .cache = &cache",
      "};", "",
      f"const lv_font_t {name} = {{",
      "    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt, .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,",
      f"    .line_height = {ascent + descent}, .base_line = {descent}, .subpx = LV_FONT_SUBPX_NONE,",
      "    .underline_position = -5, .underline_thickness = 3, .dsc = &font_dsc",
      "};", ""]
open(out, "w").write("\n".join(L))
print(name, len(bitmap), "bytes of bitmap")
